export function resolveGlossaryKey(key: string): GlossaryEntry | undefined {
  const direct = GLOSSARY_TERMS[key];
  if (direct) return direct;

  const aliased = GLOSSARY_ALIASES[key];
  if (aliased) return GLOSSARY_TERMS[aliased];

  return undefined;
}
